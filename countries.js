//Converts a two-letter ISO country code to its flag emoji (two Unicode regional
//indicator symbols), e.g. "NL" -> "🇳🇱". Avoids hand-typing ~90 emoji by hand.
export function flagForCountryCode(code) {
    if (!code || code.length !== 2) return "";
    const base = 0x1F1E6; //Regional indicator symbol letter A
    const chars = [...code.toUpperCase()].map(c => base + (c.charCodeAt(0) - 65));
    if (chars.some(cp => cp < base || cp > base + 25)) return "";
    return String.fromCodePoint(...chars);
}
